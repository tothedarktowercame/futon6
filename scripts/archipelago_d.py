def zoom_level(visible_width):
    """far (W>2000) / mid (800<W<=2000) / near (W<=800)."""
    if visible_width > ZOOM_FAR:
        return "far"
    if visible_width > ZOOM_MID:
        return "mid"
    return "near"


def contrast_ratio(c1, c2):
    """WCAG contrast ratio of two #rrggbb colours."""
    def lum(c):
        parts = [int(c[i:i+2], 16) / 255 for i in (1, 3, 5)]
        lin = [v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
               for v in parts]
        return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]
    l1, l2 = sorted((lum(c1), lum(c2)), reverse=True)
    return (l1 + 0.05) / (l2 + 0.05)


def choose_label(members, scope_counts):
    """The island's label mission: the EXPOSED member (island_membership
    only returns exposed missions — a submerged mission on the island's
    cells is never in `members`) with most scopes; ties by name."""
    return max(members, key=lambda m: (scope_counts.get(m, 0), m))


def island_labels():
    """Per cutoff: one label per island — the island's EXPOSED mission with
    most scopes ("+n" for the others) at its hub position. A submerged
    mission on the island's cells never labels it. Islets (exposed
    missions on water cells) label themselves."""
    pos = tide.fan_out(json.loads(tide.POS_EMBED.read_text()))
    dating = json.loads(tide.DATING.read_text())
    pts = tide.dating_points(dating["scopes"], pos)
    tgrid = tide.empty_grid()
    for x, y, w in tide.terrain_points(json.loads(tide.EFE_SCOPES.read_text()), pos):
        tide.gaussian_scatter(tgrid, x, y, w)
    fmax = max(max(r) for r in tgrid) or 1.0
    baseline = {(gx, gy) for gy in range(tide.GH - 1) for gx in range(tide.GW - 1)
                if tgrid[gy][gx] / fmax >= 0.03}
    low = tide.empty_grid()
    for p in pts:
        tide.gaussian_scatter(low, p["x"], p["y"], 1.0)
    theta, _ = tide.choose_theta(low, baseline)
    low_land = tide.land_cells(low, theta)
    dated_days = sorted(p["dated"][:10] for p in pts if p["dated"])
    cutoffs = tide.weekly_cutoffs(dated_days[0] if dated_days else
                                  date.today().isoformat(),
                                  date.today().isoformat())
    m_dates = defaultdict(list)
    for p in pts:
        m_dates[p["mission"]].append(p["dated"])

    def submerged(m, c):
        return tide.mission_submerged(m_dates.get(m), c)

    hub_cells = {m: (min(tide.GW - 2, max(0, int(round(x / tide.STEP)))),
                     min(tide.GH - 2, max(0, int(round(y / tide.STEP)))))
                 for m, (x, y) in pos.items()}
    counts = {m: len(v) for m, v in m_dates.items()}
    labels = {}
    for c, field, _ in tide.fields_by_cutoff(pts, cutoffs):
        land = tide.tide_land(field, low_land)
        island_of, comps, _n = ac.island_membership(land, hub_cells,
                                                    submerged, c)
        members = defaultdict(list)
        for m, iid in island_of.items():
            members[iid].append(m)
        out = []
        for iid, ms in members.items():
            lead = choose_label(ms, counts)
            x, y = pos[lead]
            name = lead[2:] if lead.startswith("M-") else lead
            text = name + (f"+{len(ms) - 1}" if len(ms) > 1 else "")
            out.append({"x": round(x), "y": round(y), "text": text,
                        "n": len(ms)})
        labels[c] = out
    return cutoffs, labels, {m: len(v) for m, v in m_dates.items()}


