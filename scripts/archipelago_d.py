def compose_page(c_data, d_data, contrast_failures):
    doc = ac.compose_page(c_data)
    # Tag the terrain fill group (first top-level group in the svg) so the
    # presets can address it; nothing else in the C page changes.
    i = doc.index('<svg id="efe-field"')
    j = doc.index('<g>', i)
    doc = doc[:j] + '<g id="d-terrain-fill">' + doc[j + 3:]
    contrast = (", ".join(f"{k} {v:.1f}:1" for k, v in contrast_failures)
                or "none")
    style = "<style>" + STYLE_CSS + "</style>"
    controls = (CONTROLS_HTML
                .replace("__SELECTORS__", ", ".join(SELECTORS_USED))
                .replace("__CONTRAST__", contrast))
    script = SCRIPT.replace(
        "__D_JSON__",
        json.dumps(d_data, separators=(",", ":")).replace("</", "<\\/"))
    return doc + style + controls + script


def main():
    t0 = time.time()
    meta, c_data = ac.build()
    cutoffs, labels, scope_counts = island_labels()
    submerged = {w["cutoff"]: sorted(w["submerged"].keys())
                 for w in c_data["weeks"]}
    d_data = {"cutoffs": cutoffs, "labels": labels, "submerged": submerged}
    failures = [(k, contrast_ratio(c, PAPER)) for k, c in STATUS_COLORS.items()
                if contrast_ratio(c, PAPER) < 3.0]
    doc = compose_page(c_data, d_data, failures)
    OUT.write_text(doc)
    added = len(doc.encode()) - BASELINE_HTML.stat().st_size
    print(f"wrote {OUT} (+{added/1e6:.2f} MB, build {time.time()-t0:.1f}s)")
    print("contrast vs paper #efe9dc:",
          ", ".join(f"{k}={contrast_ratio(c, PAPER):.2f}"
                    for k, c in STATUS_COLORS.items()))
    print("failures <3:1:", failures or "none")
    c_path = ROOT / "data" / "archipelago-C.html"
    print(f"(C page for comparison: {c_path.stat().st_size/1e6:.2f} MB)")


if __name__ == "__main__":
    main()
